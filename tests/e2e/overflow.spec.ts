test('溢出检测器正反样例：发现越界和无恢复裁切，接受省略、两行截断、原生编辑与受控滚动', async ({ page }) => {
  await page.setContent(`<style>body{margin:0}section{width:140px}p{margin:0} .ellipsis{white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.clamp{display:-webkit-box;-webkit-box-orient:vertical;-webkit-line-clamp:2;overflow:hidden}.scroll{overflow-x:auto}.wide{width:600px}input,textarea{box-sizing:border-box;width:140px}.sr{position:absolute;width:1px;height:1px;overflow:hidden;clip-path:inset(50%)}</style>
    <section><p class="ellipsis">${longText(500)}</p><p class="ellipsis"><span>${longText(500)}</span></p><p class="clamp"><span>${longText(500)}</span></p><div class="scroll"><table class="wide"><tr><td>${longText(100)}</td></tr></table></div><p class="scroll" style="white-space:nowrap">${longText(500)}</p><input value="${longText(500)}"><textarea>${longText(500)}</textarea><span class="sr">读屏保留全文</span></section>`);
  expect(await overflowFindings(page)).toEqual([]);
  await page.locator('.scroll').evaluateAll(elements => elements.forEach(el => el.scrollLeft = el.scrollWidth));
  expect(await overflowFindings(page)).toEqual([]);
  await page.locator('section').evaluate(el => el.insertAdjacentHTML('beforeend', '<p class="implicit" style="overflow-y:auto;white-space:nowrap">' + 'UNINTENDED'.repeat(100) + '</p>'));
  expect((await overflowFindings(page)).some(issue => issue.kind === 'implicit-horizontal-scroll')).toBe(true);
  await page.locator('.implicit').evaluate(el => el.remove());
  await page.locator('section').evaluate(el => el.insertAdjacentHTML('beforeend', '<p class="broken" style="white-space:nowrap">' + 'BROKEN'.repeat(100) + '</p>'));
  expect((await overflowFindings(page)).some(issue => issue.kind === 'text-container')).toBe(true);
  await page.locator('.broken').evaluate(el => (el as HTMLElement).style.overflow = 'hidden');
  expect((await overflowFindings(page)).some(issue => issue.kind === 'text-container')).toBe(true);
  await page.locator('.broken').evaluate(el => { const s = (el as HTMLElement).style; s.textOverflow = 'ellipsis'; s.display = 'inline'; });
  expect((await overflowFindings(page)).some(issue => issue.kind === 'text-container')).toBe(true);
});

